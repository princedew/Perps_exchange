CREATE OR REPLACE FUNCTION set_update_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS market (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_asset TEXT NOT NULL,
    quote_asset TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 646) PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    created_id TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_id TIMESTAMPTZ NOT NULL
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'xleverage') THEN
        CREATE TYPE xleverage AS ENUM ('1', '100', '200', '300', '400', '500', '600', '700', '800', '900', '1000', '1300', '1500', '1700', '2000');
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 429) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    leverage xleverage NOT NULL,
    balance BIGINT NOT NULL,
    created_id TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_id TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_accounts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'order_status') THEN
        CREATE TYPE order_status AS ENUM ('FILLED', 'PARTIALLY_FILLED', 'FAILED');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'order_side') THEN
        CREATE TYPE order_side AS ENUM ('BUY', 'SELL');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'order_type') THEN
        CREATE TYPE order_type AS ENUM ('LIMIT', 'MARKET');
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 385) PRIMARY KEY,
    account_id BIGINT NOT NULL,
    market_id BIGINT NOT NULL,
    leverage xleverage NOT NULL,
qty SMALLINT NOT NULL,
    side order_side NOT NULL,
    type order_type NOT NULL,
    filled_qty SMALLINT NOT NULL,
    take_profit_price BIGINT,
    stop_loss_price BIGINT,
    status order_status NOT NULL,
    created_id TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_id TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_orders_market FOREIGN KEY (market_id) REFERENCES market(id) ON DELETE SET NULL,
    CONSTRAINT fk_orders_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE SET NULL
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'position_status') THEN
        CREATE TYPE position_status AS ENUM ('OPEN', 'CLOSE', 'LIQUIDATED');
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 834) PRIMARY KEY,
    order_id BIGINT NOT NULL,
    market_id BIGINT NOT NULL,
    open_price BIGINT NOT NULL,
    close_price BIGINT,
    status position_status NOT NULL,
    pnl BIGINT,
    created_id TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_id TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_positions_market FOREIGN KEY (market_id) REFERENCES market(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS holding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    qty SMALLINT NOT NULL,
    created_id TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'transaction_status') THEN
        CREATE TYPE transaction_status AS ENUM ('DEPOSIT', 'WITHDRAW', 'TRADE_FEE', 'PROFIT', 'LOSS');
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount BIGINT NOT NULL,
    sender_account_id BIGINT NOT NULL,
    receiver_account_id BIGINT NOT NULL,
    type transaction_status NOT NULL,
    created_id TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_order_id BIGINT NOT NULL,
    seller_order_id BIGINT NOT NULL,
    created_id TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'users_modify_update_at') THEN
        CREATE TRIGGER users_modify_update_at
        BEFORE UPDATE ON users
        FOR EACH ROW
        EXECUTE FUNCTION set_update_at();
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'accounts_modify_update_at') THEN
        CREATE TRIGGER accounts_modify_update_at
        BEFORE UPDATE ON accounts
        FOR EACH ROW
        EXECUTE FUNCTION set_update_at();
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'orders_modify_update_at') THEN
        CREATE TRIGGER orders_modify_update_at
        BEFORE UPDATE ON orders
        FOR EACH ROW
        EXECUTE FUNCTION set_update_at();
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'position_modify_update_at') THEN
        CREATE TRIGGER position_modify_update_at
        BEFORE UPDATE ON positions
        FOR EACH ROW
        EXECUTE FUNCTION set_update_at();
    END IF;
END $$;


